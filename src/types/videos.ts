// 🔹 Video payloads
export interface IVideoComment {
  _id?: string; // optional, generated by backend
  text: string;
  createdBy: string;
  createdAt?: string | Date;
  createdByDetails?: {
    name: string;
    image?: string;
  };
}

export interface IVideo {
  _id: string;
  title: string;
  description?: string;
  url: string;
  thumbnail?: string;
  createdBy: string;
  partnerWatched?: boolean;
  isLiked?: boolean;
  createdByDetails?: {
    name: string;
    image?: string;
  };
  createdAt: string;
  updatedAt: string;
  comments?: IVideoComment[]; // added comments array
  totalComments: number;
}

export interface CreateVideoPayload {
  title: string;
  description?: string;
  url: string; // URL or path of the uploaded video
  createdBy: string;
  thumbnail?: string;
}

export interface AddVideoCommentPayload {
  createdBy: string;
  text: string;
}
